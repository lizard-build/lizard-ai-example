// Explicit integration check. Creates and removes only its own disposable resources.
import assert from 'node:assert/strict';
import { Runtime } from '../src/runtime.mjs';
import { Lizard } from '@lizard-build/sdk';
import { writeFile } from 'node:fs/promises';

const project = process.env.LIZARD_PROJECT_ID;
const apiKey = process.env.LIZARD_API_KEY;
if (!project || !apiKey) throw new Error('Set LIZARD_PROJECT_ID and LIZARD_API_KEY');
const volumeName = `tg-lifecycle-check-${Date.now()}`;
const recordPath = process.env.LIFECYCLE_RECORD || '/tmp/codex-telegram-lifecycle.json';
const state = new Map();
const store = { get: async (k,d) => state.get(k) ?? d, set: async (k,v) => {
  state.set(k,v);
  await writeFile(recordPath, JSON.stringify({ project, volumeName, state:Object.fromEntries(state) }), {mode:0o600});
} };
const cfg = {project,apiKey,volume:volumeName,sizeGb:2,owner:1,template:'codex',sandboxLifetimeMs:1800000};
const client = new Lizard({project,apiKey});
const runtime = new Runtime(cfg,store,client);
console.log(JSON.stringify({stage:'creating',volume:volumeName}));
const firstStarted=Date.now();
await runtime.start();
const coldMs=Date.now()-firstStarted;
const first = runtime.sandbox.sandboxId;
console.log(JSON.stringify({stage:'first-ready',sandbox:first,coldMs}));
const assetsCommand = `node -e 'const fs=require("fs"); console.log(JSON.stringify(["lizard","gh","agent-browser"].map(n=>{const p=fs.realpathSync("/usr/local/bin/"+n);return {name:n,path:p,mtime:fs.statSync(p).mtimeMs}})))'`;
const firstAssets=JSON.parse((await runtime.sandbox.process.exec(assetsCommand)).stdout);
assert.ok(firstAssets.every(a=>a.path.startsWith('/workspace/.tools/')));
await runtime.sandbox.fs.write('/workspace/roundtrip.txt','persistent-user-file');
const open = "agent-browser --session persistence-check --profile /workspace/browser-profile --args '--no-sandbox,--disable-dev-shm-usage' open https://example.com";
const browser = await runtime.sandbox.process.exec(`${open} && agent-browser --session persistence-check eval 'localStorage.setItem("botPersistenceCheck","preserved")' && agent-browser --session persistence-check close`, {timeoutMs:90000});
assert.equal(browser.exitCode,0,'first browser launch');
await runtime.retire();
console.log(JSON.stringify({stage:'first-retired',sandbox:first}));
const restoredAt=Date.now();
await runtime.start();
const warmMs=Date.now()-restoredAt;
const second=runtime.sandbox.sandboxId;
assert.notEqual(first,second);
const secondAssets=JSON.parse((await runtime.sandbox.process.exec(assetsCommand)).stdout);
assert.deepEqual(secondAssets,firstAssets,'CLI files must survive without reinstalling');
const warmBrowserLog=(await runtime.sandbox.process.exec('if test -f /tmp/browser-install.log; then cat /tmp/browser-install.log; fi')).stdout;
assert.doesNotMatch(warmBrowserLog,/Downloading|Fetched|Get:|added \d+ packages/i,'warm boot must not download browser assets');
console.log(JSON.stringify({stage:'tools-restored',coldMs,warmMs,assets:firstAssets.map(a=>a.name)}));
assert.equal(await runtime.sandbox.fs.read('/workspace/roundtrip.txt'),'persistent-user-file');
const restored=await runtime.sandbox.process.exec(`${open} && agent-browser --session persistence-check eval 'localStorage.getItem("botPersistenceCheck")' && agent-browser --session persistence-check close`,{timeoutMs:90000});
assert.equal(restored.exitCode,0);
assert.match(restored.stdout,/preserved/);
console.log(JSON.stringify({stage:'restored',sandbox:second,file:true,browserState:true}));
await runtime.retire();
await client.volumes.delete(volumeName);
console.log(JSON.stringify({stage:'complete',sandboxesRemoved:2,testVolumeRemoved:true}));
